"""
Writes src/textile.ts from a pixelated image: the grid's size and each cell's colour, row by row.

    npm run cells -- path/to/pixelated.png

The image must already be pixelated (flat cells). The grid is found from where the colours change, so
cells needn't be a whole number of pixels; each cell takes the colour at its centre. Uses macOS `sips`
to read the image (no Python packages needed).
"""
import collections
import os
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'textile.ts')
# An edge must show up on at least this many of the sampled lines to count (noise and stray pixels don't).
EDGE_VOTES = 4
SAMPLE_EVERY = 97


def read_bmp(path):
    """Converts the image to a BMP with `sips` and returns (width, height, pixel(x, y) -> (r, g, b))."""
    with tempfile.TemporaryDirectory() as tmp:
        bmp = os.path.join(tmp, 'image.bmp')
        subprocess.run(['sips', '-s', 'format', 'bmp', path, '--out', bmp], check=True, capture_output=True)
        data = open(bmp, 'rb').read()
    off = struct.unpack_from('<I', data, 10)[0]
    w, h = struct.unpack_from('<ii', data, 18)
    bpp = struct.unpack_from('<H', data, 28)[0]
    bottom_up = h > 0
    h = abs(h)
    stride = ((w * bpp // 8) + 3) & ~3
    size = bpp // 8

    def pixel(x, y):
        o = off + ((h - 1 - y) if bottom_up else y) * stride + x * size
        return data[o + 2], data[o + 1], data[o]

    return w, h, pixel


def edges(length, across, pixel_along):
    """Positions along a side where the colour changes on enough of the sampled lines across it."""
    votes = collections.Counter()
    for line in range(5, across, SAMPLE_EVERY):
        prev = pixel_along(0, line)
        for t in range(1, length):
            c = pixel_along(t, line)
            if c != prev:
                votes[t] += 1
            prev = c
    return sorted(t for t, v in votes.items() if v >= EDGE_VOTES)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    w, h, pixel = read_bmp(sys.argv[1])
    xs = [0] + edges(w, h, lambda x, y: pixel(x, y)) + [w]
    ys = [0] + edges(h, w, lambda y, x: pixel(x, y)) + [h]
    cols, rows = len(xs) - 1, len(ys) - 1
    cells = []
    for j in range(rows):
        for i in range(cols):
            r, g, b = pixel((xs[i] + xs[i + 1]) // 2, (ys[j] + ys[j + 1]) // 2)
            cells.append(f'{r:02x}{g:02x}{b:02x}')

    lines = [cells[j * cols:(j + 1) * cols] for j in range(rows)]
    body = '\n'.join(f"  '{''.join(line)}'," for line in lines)
    open(OUT, 'w').write(
        '// Generated by scripts/pixelate.py from the pixelated textile: do not edit by hand.\n'
        f'export const COLS = {cols};\n'
        f'export const ROWS = {rows};\n'
        '/** Each row of cells, left to right, as 6-digit hex colours run together. */\n'
        f'export const CELLS: readonly string[] = [\n{body}\n];\n'
    )
    print(f'{cols} × {rows} = {len(cells)} cells, {len(set(cells))} colours → src/textile.ts')


if __name__ == '__main__':
    main()
